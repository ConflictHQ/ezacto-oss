import { createPrivateKey } from 'node:crypto'
import { beforeAll, describe, expect, it } from 'vitest'
import {
  GithubHttpError,
  GithubReadClient,
  GithubReadError,
  githubAppJwt,
} from '../src/work-items/github-client.js'

const now = Date.parse('2026-10-25T12:00:00Z')
let pem: string
let publicKey: CryptoKey
beforeAll(async () => {
  const keys = await crypto.subtle.generateKey(
    {
      name: 'RSASSA-PKCS1-v1_5',
      modulusLength: 2048,
      publicExponent: new Uint8Array([1, 0, 1]),
      hash: 'SHA-256',
    },
    true,
    ['sign', 'verify'],
  )
  const bytes = new Uint8Array(await crypto.subtle.exportKey('pkcs8', keys.privateKey))
  pem = `-----BEGIN PRIVATE KEY-----\n${Buffer.from(bytes).toString('base64')}\n-----END PRIVATE KEY-----`
  publicKey = keys.publicKey
})
const token = () => ({
  token: 'private-installation-token-canary',
  expires_at: new Date(now + 3_600_000).toISOString(),
  permissions: { issues: 'read', metadata: 'read' },
  repositories: [{ id: 77, full_name: 'acme/app' }],
})
const fixture = (response: (request: Request) => Response | Promise<Response>) => {
  const requests: Request[] = []
  const client = new GithubReadClient({
    appId: '11',
    privateKey: pem,
    now: () => now,
    random: () => 0,
    fetch: async (request) => {
      requests.push(request)
      return response(request)
    },
  })
  return { client, requests }
}
describe('GitHub App read HTTP boundary', () => {
  it('[security] signs a short-lived real RS256 JWT with backdated issuance and no private key claim', async () => {
    const jwt = await githubAppJwt('11', pem, now)
    const [header, claims, signature] = jwt.split('.')
    expect(JSON.parse(Buffer.from(header!, 'base64url').toString())).toEqual({
      alg: 'RS256',
      typ: 'JWT',
    })
    expect(JSON.parse(Buffer.from(claims!, 'base64url').toString())).toEqual({
      iss: '11',
      iat: now / 1000 - 60,
      exp: now / 1000 + 540,
    })
    expect(
      await crypto.subtle.verify(
        'RSASSA-PKCS1-v1_5',
        publicKey,
        Buffer.from(signature!, 'base64url'),
        new TextEncoder().encode(`${header}.${claims}`),
      ),
    ).toBe(true)
    expect(jwt).not.toContain('PRIVATE KEY')
  })
  it('[security] imports the PKCS#1 PEM actually generated by GitHub', async () => {
    const pkcs1 = createPrivateKey(pem).export({ type: 'pkcs1', format: 'pem' }).toString()
    const jwt = await githubAppJwt('11', pkcs1, now)
    const [header, claims, signature] = jwt.split('.')
    expect(
      await crypto.subtle.verify(
        'RSASSA-PKCS1-v1_5',
        publicKey,
        Buffer.from(signature!, 'base64url'),
        new TextEncoder().encode(`${header}.${claims}`),
      ),
    ).toBe(true)
  })
  it('[security] mints only one read-only repository token and never follows a foreign pagination URL', async () => {
    const { client, requests } = fixture((request) =>
      request.method === 'POST'
        ? Response.json(token())
        : Response.json([{ id: 1 }], {
            headers: { link: '<https://evil.test/steal>; rel="next"' },
          }),
    )
    expect(
      await client.issues({
        installationId: '22',
        repositoryId: '77',
        page: 1,
        since: null,
        attempt: 1,
      }),
    ).toEqual({ issues: [{ id: 1 }], nextPage: 2 })
    expect(
      requests.map((request) => [request.method, new URL(request.url).origin, request.redirect]),
    ).toEqual([
      ['POST', 'https://api.github.com', 'manual'],
      ['GET', 'https://api.github.com', 'manual'],
    ])
    expect(await requests[0]!.json()).toEqual({
      repository_ids: [77],
      permissions: { issues: 'read', metadata: 'read' },
    })
    expect(requests[1]!.headers.get('authorization')).toBe(
      'Bearer private-installation-token-canary',
    )
    expect(requests[1]!.url).toContain(
      '/repos/acme/app/issues?state=all&sort=updated&direction=asc&per_page=100&page=1',
    )
  })
  it('[security] refuses broad or wrong-repository tokens before the first issue GET', async () => {
    for (const over of [
      { repositories: [{ id: 78 }] },
      { repositories: [{ id: 77 }, { id: 78 }] },
      { permissions: { issues: 'write', metadata: 'read' } },
      { expires_at: new Date(now - 1).toISOString() },
    ]) {
      const { client, requests } = fixture(() => Response.json({ ...token(), ...over }))
      await expect(
        client.issues({
          installationId: '22',
          repositoryId: '77',
          page: 1,
          since: null,
          attempt: 1,
        }),
      ).rejects.toMatchObject({ code: 'invalid_response' })
      expect(requests).toHaveLength(1)
    }
  })
  it('[unit] validates installation account and repository immutable IDs without returning tokens', async () => {
    const { client } = fixture((request) =>
      request.method === 'POST'
        ? Response.json(token())
        : request.url.endsWith('/app/installations/22')
          ? Response.json({
              id: 22,
              account: { id: 33 },
              suspended_at: null,
              repository_selection: 'selected',
              permissions: { issues: 'read' },
            })
          : Response.json({ id: 77, owner: { id: 33 }, full_name: 'Owned/Disposable' }),
    )
    expect(await client.installation('22')).toEqual({
      accountId: '33',
      repositorySelection: 'selected',
    })
    expect(await client.repository('22', '77')).toEqual({
      repositoryId: '77',
      accountId: '33',
      fullName: 'Owned/Disposable',
    })
  })
  it('[unit] returns rate-limit decision once without sleeping, retrying, or exposing provider text', async () => {
    const { client, requests } = fixture(
      () =>
        new Response('private-provider-message-canary', {
          status: 429,
          headers: { 'retry-after': '60' },
        }),
    )
    const error = await client
      .issues({ installationId: '22', repositoryId: '77', page: 1, since: null, attempt: 1 })
      .catch((error: unknown) => error)
    expect(error).toBeInstanceOf(GithubHttpError)
    expect(error).toMatchObject({
      status: 429,
      decision: { action: 'retry', notBefore: now + 60_000 },
    })
    expect(String(error)).not.toContain('canary')
    expect(requests).toHaveLength(1)
  })
  it('[security] refuses redirect, malformed and oversized responses without raw response data in errors', async () => {
    for (const response of [
      new Response('secret-canary', { status: 302, headers: { location: 'https://evil.test' } }),
      new Response('secret-canary'),
      new Response('x'.repeat(2_097_153)),
    ]) {
      const { client, requests } = fixture(() => response)
      const error = await client.installation('22').catch((error: unknown) => error)
      expect(error instanceof GithubReadError || error instanceof GithubHttpError).toBe(true)
      expect(String(error)).not.toContain('secret-canary')
      expect(requests).toHaveLength(1)
    }
  })
  it('[security] refuses attacker-controlled ID/path/query before transport and isolates raw transport failures', async () => {
    const { client, requests } = fixture(() => {
      throw new Error('private-url-canary')
    })
    await expect(client.installation('../escape')).rejects.toMatchObject({
      code: 'invalid_configuration',
    })
    expect(requests).toHaveLength(0)
    const error = await client.installation('22').catch((error: unknown) => error)
    expect(error).toMatchObject({ code: 'transport_unavailable' })
    expect(String(error)).not.toContain('private-url-canary')
  })
})

describe('GitHub administrator repository discovery', () => {
  it('lists only active read-enabled installations and bounded metadata-only repository names', async () => {
    const { client, requests } = fixture((request) => {
      const url = new URL(request.url)
      if (url.pathname === '/app/installations')
        return Response.json(
          [
            {
              id: 22,
              account: { id: 33, login: 'owned' },
              permissions: { issues: 'read' },
              repository_selection: 'selected',
              suspended_at: null,
            },
            {
              id: 23,
              account: { id: 33, login: 'suspended' },
              permissions: { issues: 'read' },
              repository_selection: 'selected',
              suspended_at: '2026-10-01T00:00:00Z',
            },
          ],
          { headers: { link: '<https://foreign.test/>; rel="next"' } },
        )
      if (url.pathname === '/app/installations/22')
        return Response.json({
          id: 22,
          account: { id: 33 },
          suspended_at: null,
          permissions: { issues: 'read' },
          repository_selection: 'selected',
        })
      if (request.method === 'POST')
        return Response.json({
          token: 'metadata-only-canary',
          expires_at: new Date(now + 3600000).toISOString(),
          permissions: { metadata: 'read' },
        })
      return Response.json({
        repositories: [{ id: 77, full_name: 'owned/disposable', description: 'not retained' }],
      })
    })
    expect(await client.installations()).toEqual({
      items: [{ id: '22', account: 'owned', repository_selection: 'selected' }],
      next_page: 2,
    })
    expect(await client.repositories('22')).toEqual({
      items: [{ id: '77', full_name: 'owned/disposable' }],
      next_page: null,
    })
    expect(await requests[2]!.json()).toEqual({ permissions: { metadata: 'read' } })
    expect(
      requests.every((request) => new URL(request.url).origin === 'https://api.github.com'),
    ).toBe(true)
    expect(requests[3]!.url).toBe(
      'https://api.github.com/installation/repositories?per_page=100&page=1',
    )
  })
  it('refuses broader discovery tokens before listing repositories', async () => {
    const { client, requests } = fixture((request) =>
      request.method === 'POST'
        ? Response.json({
            token: 'broad-canary',
            expires_at: new Date(now + 3600000).toISOString(),
            permissions: { metadata: 'read', issues: 'write' },
          })
        : Response.json({
            id: 22,
            account: { id: 33 },
            suspended_at: null,
            permissions: { issues: 'read' },
            repository_selection: 'selected',
          }),
    )
    await expect(client.repositories('22')).rejects.toMatchObject({ code: 'invalid_response' })
    expect(requests).toHaveLength(2)
  })
})
