import { readFile, readdir } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { describe, expect, it, vi } from 'vitest'
import {
  cssCustomProperty,
  defaultTheme,
  loadActiveThemeFonts,
  slot,
  themeFontNames,
  themeManifest,
  themeSlotNames,
} from '../src/index.js'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

const filesUnder = async (directory: string): Promise<string[]> => {
  const entries = await readdir(directory, { withFileTypes: true })
  const paths = await Promise.all(
    entries.map((entry) => {
      const path = resolve(directory, entry.name)
      return entry.isDirectory() ? filesUnder(path) : Promise.resolve([path])
    }),
  )
  return paths.flat()
}

describe('D16 theme token contract', () => {
  it('[unit] snapshot-compiles the precision theme to semantic CSS properties', async () => {
    const css = await readFile(resolve(root, 'generated', 'themes.css'), 'utf8')
    expect(css).toMatchInlineSnapshot(`
      "/* Generated by scripts/compile-theme-tokens.mjs. Do not edit. */
      :root, [data-ez-theme="precision"] {
        --ez-ground: #FFFFFF;
        --ez-surface: #F9FAFB;
        --ez-border: #E5E7EB;
        --ez-ink: #1A1A2E;
        --ez-muted: #5F6673;
        --ez-action: #254FE8;
        --ez-action-fg: #FFFFFF;
        --ez-live: #15803D;
        --ez-data: #254FE8;
        --ez-money: #FDF7EE;
        --ez-status-bg: #F1F5F9;
        --ez-status-fg: #5F6673;
        --ez-ink-2: #374151;
        --ez-orange-tint: #EFF3FF;
        --ez-blue-light: #C7D2FE;
        --ez-red: #B91C1C;
        --ez-amber: #B45309;
        --ez-amber-bg: #FEF3C7;
        --ez-live-text: #15803D;
        --ez-surface-2: #F3F4F6;
        --ez-row-hover: #EFF3FF;
        --ez-font-display: "Google Sans Flex";
        --ez-font-body: "Google Sans Flex";
        --ez-font-mono: "IBM Plex Mono";
        --ez-radius: 8px;
      }
      "
    `)
    expect(defaultTheme).toBe('precision')
    expect(Object.keys(themeManifest)).toEqual(['precision'])
    expect(Object.keys(themeManifest.precision.colors)).toEqual([...themeSlotNames])
    expect(Object.keys(themeManifest.precision.fonts)).toEqual([...themeFontNames])
    expect(themeSlotNames.map(cssCustomProperty)).toContain('--ez-action-fg')
    expect(slot('live')).toBe('var(--ez-live)')
  })

  it('[unit] carries the nested surface and the row-hover tint as contract slots', () => {
    // Neither value can be re-derived from the rest of the palette by reading
    // it, so both are pinned here. #292 recorded the first values; the
    // 2026-10 tracker design replaced them.
    //
    // `surface_2` is a panel inside a card -- a toolbar inside a workspace, a
    // summary band inside a list. It is the next rung of the grey ramp
    // `surface` already stands on -- #FFFFFF, #F9FAFB, #F3F4F6, the design's
    // own greys -- at about the same distance again, so nesting reads as one
    // more rung of one ramp rather than as a second colour.
    const channels = (from: string, to: string): number[] =>
      [1, 3, 5].map(
        (index) =>
          Number.parseInt(from.slice(index, index + 2), 16) -
          Number.parseInt(to.slice(index, index + 2), 16),
      )
    const { ground, surface, surface_2: nested, row_hover: rowHover } =
      themeManifest.precision.colors
    expect(channels(ground, surface)).toEqual([6, 5, 4])
    expect(channels(ground, nested)).toEqual([12, 11, 9])

    // `row_hover` is the design's pale blue, #EFF3FF: a high-lightness tint of
    // the brand blue that `data` and the billable bar are drawn in.
    expect(rowHover).toBe('#EFF3FF')

    expect(themeSlotNames).toContain('surface_2')
    expect(themeSlotNames).toContain('row_hover')
    expect(cssCustomProperty('surface_2')).toBe('--ez-surface-2')
    expect(cssCustomProperty('row_hover')).toBe('--ez-row-hover')
  })

  it('[unit] requests only the active theme font stylesheet', async () => {
    const request = vi.fn<(href: string) => Promise<void>>().mockResolvedValue(undefined)
    await loadActiveThemeFonts('precision', request)
    expect(request).toHaveBeenCalledTimes(1)
    expect(request).toHaveBeenCalledWith(
      'https://fonts.googleapis.com/css2?family=Google+Sans+Flex:wght@400;500;600;700;900&family=IBM+Plex+Mono:wght@400;500;600;700;900&display=swap',
    )
    expect(request.mock.calls.flat().join(' ')).not.toMatch(/Space|Roboto|Unica/u)
  })

  it('[unit] rejects literal colors from component and shell source', async () => {
    const sourceFiles = (
      await Promise.all([
        filesUnder(resolve(root, 'src', 'components')),
        filesUnder(resolve(root, 'src', 'shell')),
        filesUnder(resolve(root, 'src', 'week-grid')),
      ])
    )
      .flat()
      .filter((path) => path.endsWith('.ts') || path.endsWith('.tsx') || path.endsWith('.css'))
    expect(sourceFiles.length).toBeGreaterThan(0)
    for (const path of sourceFiles) {
      const source = await readFile(path, 'utf8')
      expect(source, path).not.toMatch(/#[0-9a-fA-F]{3,8}\b/u)
    }
  })

  it('[unit] spends every token it declares, or names why not', async () => {
    // A design-system slot that nothing references is not a token, it is a
    // decision nobody applied -- `surface_2` and `row_hover` both sat in the
    // contract and in the contrast gate while the stylesheet used neither, so
    // the grouped-table band and the row hover stayed the wrong colour and
    // every gate still passed.
    //
    // These are the same shape and are not guessed at here: a slot's purpose is
    // a decision, and inventing one is how a token comes to mean two things.
    // The list is a ratchet -- it may shrink, and a new name appearing in it is
    // a token that shipped without a job.
    //
    // `amber` and `amber_bg` came off it with the invoice-configuration screen,
    // which had the thing they are unambiguously for: a warning that is not yet
    // an error -- a sender the provider has not finished verifying, and a
    // template naming a variable that does not exist. `money` stayed on it. A
    // verified sender wanted a positive colour and money-green was to hand, but
    // that would have made the token mean two things; the screen marks only the
    // states needing attention instead.
    // `blue_light` came off it with the brand-asset control (#489): the dark
    // preview tile paints `--ez-ink`, and its hint needs a muted colour that
    // stays legible on that ground, which is the job the token was holding a
    // colour for.
    //
    // The last two came off together, because their jobs are the same decision:
    // `money` is the band behind the invoice totals, so the totals read as money
    // rather than as one more list; `ink_2` is the label ink on that band. That
    // is what separates it from `muted`, which is tuned against the page ground
    // -- the distinction the earlier note worried they lacked. The list is now
    // empty and stays a ratchet: a new name in it is a token that shipped
    // without a job.
    const awaitingAPurpose: string[] = []
    const stylesheet = await readFile(resolve(root, 'src', 'shell', 'shell.css'), 'utf8')
    const unspent = themeSlotNames.filter(
      (name) => !stylesheet.includes(`var(${cssCustomProperty(name)})`),
    )
    expect(unspent).toEqual(awaitingAPurpose)
  })

  it('[unit] gives every page surface exactly one measure', async () => {
    // `page--grid` and `page--document` replaced nine hand-written max-width
    // caps, and were then applied to nothing -- so settings forms ran the full
    // width of the monitor. Every page container declares which surface it is.
    const renderers = (await filesUnder(resolve(root, 'src')))
      .filter((path) => path.endsWith('render.ts') && !path.includes('generated'))
    const containers: string[] = []
    for (const path of renderers) {
      const source = await readFile(path, 'utf8')
      for (const [, classes] of source.matchAll(/<main class="(app-content[^"]*)"/gu)) {
        containers.push(`${path}: ${classes}`)
      }
    }
    expect(containers.length).toBeGreaterThan(0)
    // Three measures: grid for tables, document for prose, and settings for
    // the pages that carry forms and fact lists at a width between (issue 800).
    const measures = ['page--grid', 'page--document', 'page--settings']
    for (const container of containers) {
      const declared = measures.filter((measure) => container.includes(measure))
      expect(declared, container).toHaveLength(1)
    }
  })

  it('[unit] gives navigation a hover state, not only a current state', async () => {
    // A tab that says which one you are on and nothing about which one you are
    // about to choose reads as a label rather than a control.
    const stylesheet = await readFile(resolve(root, 'src', 'shell', 'shell.css'), 'utf8')
    expect(stylesheet).toMatch(/\.tabstrip a:hover/u)
    expect(stylesheet).toMatch(/\.tabstrip\.view-switch a:hover/u)
  })
})
