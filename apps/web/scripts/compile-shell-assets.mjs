import { existsSync } from 'node:fs'
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const outputPath = resolve(root, 'src', 'generated', 'shell-assets.ts')
const check = process.argv.includes('--check')

const bundle = await build({
  entryPoints: [resolve(root, 'src', 'shell', 'browser.ts')],
  bundle: true,
  write: false,
  platform: 'browser',
  format: 'iife',
  target: 'es2022',
  conditions: ['browser', 'development'],
  minify: true,
  legalComments: 'none',
  charset: 'utf8',
})
const javascript = bundle.outputFiles?.[0]?.text
if (javascript === undefined)
  throw new Error('shell compiler did not emit JavaScript')

const [themeCss, shellCss] = await Promise.all([
  readFile(resolve(root, 'generated', 'themes.css'), 'utf8'),
  readFile(resolve(root, 'src', 'shell', 'shell.css'), 'utf8'),
])
const stylesheet = `${themeCss.trim()}\n${shellCss.trim()}\n`
const output = [
  '// Generated by scripts/compile-shell-assets.mjs. Do not edit.',
  `export const shellStylesheet = ${JSON.stringify(stylesheet)}`,
  `export const shellJavascript = ${JSON.stringify(javascript.trim())}`,
  '',
].join('\n')

if (check) {
  if (
    !existsSync(outputPath) ||
    (await readFile(outputPath, 'utf8')) !== output
  ) {
    throw new Error(
      'src/generated/shell-assets.ts is stale; run npm run shell:generate',
    )
  }
} else {
  await writeFile(outputPath, output)
}
