import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import {
  PRIVACY_FRAMEWORK_CATALOG,
  PRIVACY_REFERENCE_REVIEWED_ON,
} from "../packages/core/dist/index.js";

const target = fileURLToPath(
  new URL("../docs/us-state-privacy-reference.md", import.meta.url),
);
const states = PRIVACY_FRAMEWORK_CATALOG.filter(
  (entry) => entry.state !== null,
);
const status = (entry) =>
  ({
    in_effect: "In effect at review date",
    enacted_future: `Enacted; principal effective date ${entry.effectiveOn}`,
    sector_specific: "Sector-specific example",
    operator_assessment:
      "Operator assessment; no comprehensive-act status asserted",
  })[entry.status];
const content = `<!-- Generated by scripts/generate-privacy-reference.mjs from packages/core/src/privacy-frameworks.ts. -->
# US state privacy reference

Reviewed **${PRIVACY_REFERENCE_REVIEWED_ON}**. The settings catalog includes all 50
states and the District of Columbia. A jurisdiction's presence does not assert
that its law applies to eZacto, to every operator, or to every record. Selecting
it records an operator assessment or preparation decision, not compliance,
consent, a waiver, a legal exemption or automatic erasure. No selection may
reduce a right or obligation that applies by law.

The reference identifies enacted comprehensive consumer privacy laws and the
Florida Digital Bill of Rights separately from selected sector-specific examples.
For other jurisdictions, it provides an assessment entry without asserting that
no comprehensive law, privacy protection, pending bill or other obligation
exists. Use the linked [current legislation tracker](https://www.ncsl.org/technology-and-communication/consumer-privacy-legislation-database)
and official state sources. The examples do not enumerate all state, federal,
territorial, local or sector-specific privacy and security duties.

Future dates below concern the cited law's principal start, not every amendment,
phase, cure period or enforcement date. Verify the enacted version; a bill's
introduced or floor version can contain a different date. Current-law rows are
as of the review date, not a live legal-status service.

| Jurisdiction | Law or assessment entry | Status at review | Reference |
| --- | --- | --- | --- |
${states.map((entry) => `| ${entry.state} | ${entry.label} | ${status(entry)} | [${entry.status === "operator_assessment" ? "Legislation tracker" : "Official source"}](${entry.url}) |`).join("\n")}

## Apply the reference to the actual processing

For each relevant jurisdiction, document resident and territorial scope, entity
thresholds and exemptions, and whether records concern a consumer, employee,
contractor or business contact. Evaluate each record and processing purpose.
Employment exclusions in some consumer statutes are not a universal employment
privacy exemption. Florida's Digital Bill of Rights has an unusually narrow
controller definition and separately scoped provisions; Florida incorporation
alone does not determine applicability. A comprehensive consumer statute is not
the only source of privacy duties: Illinois biometrics, Washington consumer
health data, Nevada online privacy, security, breach notification and other
sector-specific requirements need their own assessment where relevant.

Assess access, correction, deletion, portability, consent, opt-outs (including
recognized preference signals), appeals, notices, processor contracts and
security obligations where applicable. Do not assume each law grants the same
rights, has identical deadlines or permits the same retention exceptions.
These policy settings do not implement all of those workflows or certify that
the product or a particular deployment complies with every listed law.

Retain only records necessary for a documented purpose and permitted basis,
with a period or release condition and a review process. Preserve identified
work and invoice/payment links only where justified. Include required backups,
exports, attachments and downstream recipients in the assessment. See the
[operator erasure and retention guide](account-erasure-retention.md).

## Maintenance

Before each release that changes personal-data processing, and before an
operator republishes a policy, review relevant official sources for new laws,
amendments, effective dates, regulations and court orders. Also review when
entering a new jurisdiction or changing vendors, record types or retention.
This is an operator/release responsibility, not an automatic monitoring service.

Update the shared catalog and its review date, then run \`npm run privacy:generate\`.
The same identifiers feed backend validation, the OpenAPI enum and the web
checkboxes. \`npm run contract:generate\` refreshes API artifacts and this reference;
the contract check detects documentation drift. Preserve existing identifiers
because historical policies use them. Do not silently change saved operator
selections or treat a new catalog entry as a new consent or retention permission.
`;
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8").catch(() => "")) !== content) {
    throw new Error(
      "Privacy reference is out of date. Run npm run privacy:generate.",
    );
  }
} else {
  await writeFile(target, content);
  console.log(`generated ${target}`);
}
